"""Build docs/RESULTS.md from the saved result files (no number is typed by hand).

    python scripts/make_results.py
Inputs: outputs/eval/detrac_summary.csv, outputs/bench/pi_sim.json, outputs/bench/calibration.json,
        outputs/eval/alerts_summary.csv (+ grace sweep), annotations/islab_events.csv
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

LABELS = {"yolov8n": "YOLOv8n", "yolo11n": "YOLO11n", "yolo26n": "YOLO26n"}


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    md = ["# Results", "",
          "Generated by `scripts/make_results.py` from the files in `outputs/`. "
          "Figures (400 DPI PNG + PDF) are in `outputs/figures/` (`scripts/make_figures.py`).", ""]

    # 1. detection accuracy
    f = Path("outputs/eval/detrac_summary.csv")
    if f.exists():
        rows = {}
        for r in csv.DictReader(open(f, encoding="utf-8")):
            rows[(r["label"], r["subset"])] = r
        md += ["## 1. Vehicle detection accuracy (UA-DETRAC, 842 sampled test frames, 8 sequences)", "",
               "All DETRAC vehicle types = one class; COCO car/motorcycle/bus/truck merged; detections in "
               "DETRAC ignored regions discarded. imgsz 640, FP32 PyTorch weights.", ""]
        body = []
        for m in LABELS:
            if (m, "all") in rows:
                a = rows[(m, "all")]
                per = " / ".join(rows[(m, s)]["mAP50_95"] for s in ("sunny", "cloudy", "rainy", "night") if (m, s) in rows)
                body.append([LABELS[m], a["P"], a["R"], a["F1"], a["mAP50"], a["mAP50_95"], per])
        md += [table(["Model", "P", "R", "F1", "mAP@0.5", "mAP@0.5:0.95", "mAP@0.5:0.95 sunny / cloudy / rainy / night"], body), ""]

    # 2. calibration
    f = Path("outputs/bench/calibration.json")
    if f.exists():
        c = json.loads(f.read_text())
        md += ["## 2. Raspberry Pi 5 calibration of the edge container", "",
               f"Reference: {c['reference']} â€” YOLO26n PyTorch {c['pi5_inference_ms']} ms/image. "
               f"Calibrated CPU limit: **{c['calibrated_cpus']} CPUs** (4 inference threads, 4 GB). "
               "Measured on the laptop on mains power in Windows 'Best performance' mode, median of 3 runs.", "",
               table(["--cpus", "inference ms (median)", "runs (ms)"],
                     [[s["cpus"], s["inference_ms"], ", ".join(f"{x:.0f}" for x in s["runs_ms"])] for s in c["sweep"]]), ""]

    # 3. speed by model x format
    f = Path("outputs/bench/pi_sim.json")
    if f.exists():
        rows = json.loads(f.read_text())
        md += ["## 3. Speed on the simulated Raspberry Pi 5 (calibrated container)", "",
               "coco128 val protocol, batch 1, FP32, 640 px; inference time only (pre/post-processing excluded, "
               "as in the published table); median of 3 runs.", ""]
        body = []
        for m in LABELS:
            for fmt in ("pytorch", "onnx", "ncnn"):
                r = next((r for r in rows if r["model"] == m and r["format"] == fmt), None)
                if r:
                    pub = f"{r['pi5_published_ms']}" if r.get("pi5_published_ms") else "â€“"
                    err = f"{r['error_pct']:+.1f}%" if r.get("error_pct") is not None else "â€“"
                    body.append([LABELS[m], fmt.upper() if fmt != "pytorch" else "PyTorch", r["inference_ms"],
                                 f"{1000 / r['inference_ms']:.1f}", r["map50_95_coco128"], pub, err])
        md += [table(["Model", "Format", "ms / image", "FPS (inference)", "mAP@0.5:0.95 coco128",
                      "Real Pi 5 (ms)", "Simulation error"], body), "",
               "PyTorch is the calibration format, so its error is small by construction for YOLO26n; ONNX and NCNN "
               "test whether the container predicts other runtimes. NCNN is tuned for ARM NEON and is far slower "
               "on the x86 container than on the real Pi, so format rankings from an x86 simulation do not transfer "
               "to ARM.", ""]

    # 4. alert evaluation
    f = Path("outputs/eval/alerts_summary.csv")
    if f.exists():
        rows = list(csv.DictReader(open(f, encoding="utf-8")))
        gt = [ln for ln in Path("annotations/islab_events.csv").read_text(encoding="utf-8").splitlines()
              if ln and not ln.startswith("#")][1:]
        md += ["## 4. Alert quality on the ISLab videos", "",
               f"Ground truth: `annotations/islab_events.csv` ({len(gt)} stationary-vehicle events, AI-labelled "
               "from raw frames â€” see the provenance header). Detections and tracks were computed once at 3 frames/s "
               "(the rate of the calibrated edge node) and replayed through each variant. "
               "precision = TP / all alerts (false alarms and duplicates count against it), recall = TP / GT violations, "
               "delay = alert time âˆ’ (stop time + T).", ""]
        for split in ("test", "dev", "all"):
            sub = [r for r in rows if r["split"] == split]
            if not sub:
                continue
            md += [f"### {split} videos", "",
                   table(["T (s)", "Variant", "Alerts", "TP", "False alarms", "Duplicates", "Missed", "Precision",
                          "Recall", "F1", "Mean delay (s)"],
                         [[r["T"], r["variant"], r["alerts"], r["TP"], r["FP"], r["duplicates"], r["missed"],
                           r["precision"], r["recall"], r["F1"], r["mean_delay_s"] or "â€“"] for r in sub]), ""]
    g = Path("outputs/eval/grace_sweep.json")
    if g.exists():
        s = json.loads(g.read_text())
        md += ["### Dev-set tuning of the occlusion grace period", "",
               table(["grace_s", "dev F1 (T=60, full system)", "dev duplicates"], [[r["grace_s"], r["F1"], r["duplicates"]] for r in s["rows"]]),
               "", f"Chosen: **grace_s = {s['chosen']}** (highest dev F1, ties to the smaller value); test results above use it.", ""]

    Path("docs").mkdir(exist_ok=True)
    Path("docs/RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()

